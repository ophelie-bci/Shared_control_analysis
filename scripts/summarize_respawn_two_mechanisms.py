"""
Summarize two Respawn failure mechanisms from generated reorientation tables.

Mechanism 1: trial.modelVelocity never provides sustained new-target evidence.
Mechanism 2: when trial.modelVelocity does reorient, compare BCI latency. Then
use the shared-control input/output log to quantify BCI-to-executed lag.

Inputs are generated by the Respawn scripts with the final manuscript inclusion
rule: answer 1 is success; unsuccessful outcomes are restricted to {3,5,6};
codes {4,9,10} are excluded.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats
import statsmodels.formula.api as smf


PROJECT_ROOT = Path(__file__).resolve().parent.parent


def summarize_two_mechanisms() -> tuple[pd.DataFrame, pd.DataFrame]:
    tables_dir = PROJECT_ROOT / "tables"
    model_summary_path = tables_dir / "respawn_bci_reorientation_by_outcome_summary.csv"
    model_tests_path = tables_dir / "respawn_bci_reorientation_correct_vs_incorrect.csv"
    model_trials_path = tables_dir / "respawn_bci_reorientation_by_outcome_trials.csv"
    lag_tests_path = tables_dir / "respawn_reorientation_lag_summary.csv"
    lag_trials_path = tables_dir / "respawn_reorientation_lag_by_trial.csv"
    for path in (model_summary_path, model_tests_path, model_trials_path, lag_tests_path, lag_trials_path):
        if not path.exists():
            raise FileNotFoundError(f"Missing {path}")

    model_summary = pd.read_csv(model_summary_path)
    model_tests = pd.read_csv(model_tests_path)
    model_trials = pd.read_csv(model_trials_path)
    lag_tests = pd.read_csv(lag_tests_path)
    lag_trials = pd.read_csv(lag_trials_path)

    rows = []
    for _, row in model_summary.iterrows():
        rows.append({
            "condition": "Shared control" if row["condition"] == "AI" else "BCI-only",
            "outcome": row["outcome"],
            "n_trials": int(row["n_trials"]),
            "n_bci_reoriented": int(row["n_crossed"]),
            "pct_bci_reoriented_within_2s": 100.0 * float(row["crossing_fraction"]),
            "pct_bci_failed_reorientation_within_2s": 100.0 * float(row["failure_to_cross_fraction"]),
            "median_bci_reorientation_latency_ms": float(row["median_t_bci_modelvelocity_ms"]),
            "iqr_bci_reorientation_latency_ms": float(row["iqr_t_bci_modelvelocity_ms"]),
        })
    summary = pd.DataFrame(rows)

    comparisons = []
    for _, row in model_tests.iterrows():
        comparisons.append({
            "source": "trial.modelVelocity",
            "condition": "Shared control" if row["condition"] == "AI" else "BCI-only",
            "subset": "BCI reoriented within 2 s",
            "metric": "bci_reorientation_latency_ms",
            "n_correct": int(row["n_correct_crossed"]),
            "n_incorrect": int(row["n_incorrect_crossed"]),
            "correct_median": float(row["correct_median_ms"]),
            "incorrect_median": float(row["incorrect_median_ms"]),
            "incorrect_minus_correct_median": float(row["incorrect_minus_correct_median_ms"]),
            "ols_interaction_coefficient_ms": np.nan,
            "p_value": float(row["p_value"]),
        })

    interaction = _latency_interaction(model_trials)
    comparisons.append({
        "source": "trial.modelVelocity",
        "condition": "Shared control vs BCI-only",
        "subset": "BCI reoriented within 2 s",
        "metric": "latency_penalty_interaction",
        "n_correct": int(interaction["n_correct"]),
        "n_incorrect": int(interaction["n_incorrect"]),
        "correct_median": np.nan,
        "incorrect_median": np.nan,
        "incorrect_minus_correct_median": float(interaction["median_penalty_difference_ms"]),
        "ols_interaction_coefficient_ms": float(interaction["ols_interaction_coefficient_ms"]),
        "p_value": float(interaction["p_value"]),
    })

    lag = lag_tests[lag_tests["metric"] == "controller_lag_ms"].iloc[0]
    comparisons.append({
        "source": "aiVelocities Input/Output",
        "condition": "Shared control",
        "subset": "BCI and executed velocity reoriented within 2 s",
        "metric": "bci_to_executed_lag_ms",
        "n_correct": int(lag["n_successful"]),
        "n_incorrect": int(lag["n_unsuccessful"]),
        "correct_median": float(lag["successful_median"]),
        "incorrect_median": float(lag["unsuccessful_median"]),
        "incorrect_minus_correct_median": float(lag["unsuccessful_minus_successful_median"]),
        "ols_interaction_coefficient_ms": np.nan,
        "p_value": float(lag["p_value"]),
        })
    comparison = pd.DataFrame(comparisons)

    controller_delay = _controller_delay_table(lag_trials, lag)

    summary.to_csv(tables_dir / "respawn_two_part_bci_reorientation_table.csv", index=False)
    comparison.to_csv(tables_dir / "respawn_two_part_bci_latency_tests.csv", index=False)
    controller_delay.to_csv(tables_dir / "respawn_two_part_controller_delay_table.csv", index=False)
    summary.to_csv(tables_dir / "respawn_two_mechanism_summary.csv", index=False)
    comparison.to_csv(tables_dir / "respawn_two_mechanism_reoriented_subset_tests.csv", index=False)
    write_statement(summary, comparison, controller_delay)
    return summary, comparison


def _bool_series(s: pd.Series) -> pd.Series:
    return s.astype(str).str.lower().isin(["true", "1", "yes"])


def _latency_interaction(model_trials: pd.DataFrame) -> dict:
    rows = model_trials.copy()
    rows = rows[_bool_series(rows["bci_crossed_within_window"])].copy()
    rows["latency_ms"] = pd.to_numeric(rows["t_bci_modelvelocity_ms"], errors="coerce")
    rows = rows.dropna(subset=["latency_ms", "condition", "outcome"])
    rows["shared_control"] = (rows["condition"] == "AI").astype(int)
    rows["incorrect"] = (rows["outcome"] == "incorrect").astype(int)
    fit = smf.ols("latency_ms ~ shared_control * incorrect", data=rows).fit(cov_type="HC3")

    med = rows.groupby(["condition", "outcome"])["latency_ms"].median()
    ai_penalty = med[("AI", "incorrect")] - med[("AI", "correct")]
    no_ai_penalty = med[("No AI", "incorrect")] - med[("No AI", "correct")]
    term = "shared_control:incorrect"
    return {
        "n_correct": int((rows["outcome"] == "correct").sum()),
        "n_incorrect": int((rows["outcome"] == "incorrect").sum()),
        "ai_incorrect_minus_correct_median_ms": float(ai_penalty),
        "bci_only_incorrect_minus_correct_median_ms": float(no_ai_penalty),
        "median_penalty_difference_ms": float(ai_penalty - no_ai_penalty),
        "ols_interaction_coefficient_ms": float(fit.params[term]),
        "p_value": float(fit.pvalues[term]),
    }


def _median_iqr(values: pd.Series) -> tuple[float, float]:
    vals = pd.to_numeric(values, errors="coerce").dropna()
    if vals.empty:
        return np.nan, np.nan
    return float(np.nanmedian(vals)), float(np.nanpercentile(vals, 75) - np.nanpercentile(vals, 25))


def _controller_delay_table(lag_trials: pd.DataFrame, lag_test: pd.Series) -> pd.DataFrame:
    rows = lag_trials.copy()
    rows = rows[_bool_series(rows["bci_crossed_within_window"]) & _bool_series(rows["exec_crossed_within_window"])].copy()
    out_rows = []
    for outcome, label in (("successful", "Correct, both reoriented"), ("unsuccessful", "Incorrect, both reoriented")):
        group = rows[rows["outcome"] == outcome]
        median, iqr = _median_iqr(group["controller_lag_ms"])
        out_rows.append({
            "shared_control_subset": label,
            "n_trials": int(len(group)),
            "median_bci_to_executed_lag_ms": median,
            "iqr_bci_to_executed_lag_ms": iqr,
        })
    table = pd.DataFrame(out_rows)
    table["incorrect_minus_correct_median_ms"] = np.nan
    table["p_value"] = np.nan
    if len(table) == 2:
        table.loc[1, "incorrect_minus_correct_median_ms"] = float(lag_test["unsuccessful_minus_successful_median"])
        table.loc[1, "p_value"] = float(lag_test["p_value"])
    return table


def write_statement(summary: pd.DataFrame, comparison: pd.DataFrame, controller_delay: pd.DataFrame) -> None:
    out = PROJECT_ROOT / "tables" / "respawn_two_mechanism_statement.md"
    ai_summary = summary[summary["condition"] == "Shared control"]
    correct = ai_summary[ai_summary["outcome"] == "correct"].iloc[0]
    incorrect = ai_summary[ai_summary["outcome"] == "incorrect"].iloc[0]
    bci_test = comparison[
        (comparison["condition"] == "Shared control")
        & (comparison["metric"] == "bci_reorientation_latency_ms")
    ].iloc[0]
    no_ai_test = comparison[
        (comparison["condition"] == "BCI-only")
        & (comparison["metric"] == "bci_reorientation_latency_ms")
    ].iloc[0]
    interaction = comparison[comparison["metric"] == "latency_penalty_interaction"].iloc[0]
    lag_test = comparison[comparison["metric"] == "bci_to_executed_lag_ms"].iloc[0]

    lines = [
        "# Respawn Failure Mechanism Decomposition",
        "",
        "Shared-control Respawn failures were split into two mechanisms.",
        "",
        "## 1. Stable decoded-BCI reorientation",
        "",
        f"- Incorrect shared-control trials without sustained BCI reorientation within 2 s: {incorrect['pct_bci_failed_reorientation_within_2s']:.1f}% ({int(incorrect['n_trials'] - incorrect['n_bci_reoriented'])}/{int(incorrect['n_trials'])}).",
        f"- Correct shared-control trials without sustained BCI reorientation within 2 s: {correct['pct_bci_failed_reorientation_within_2s']:.1f}% ({int(correct['n_trials'] - correct['n_bci_reoriented'])}/{int(correct['n_trials'])}).",
        "",
        "These non-reorientation failures cannot be attributed solely to RT-V2 temporal inertia because the decoded BCI command did not provide a stable new-target switch within the analysis window.",
        "",
        "## 2. Latency after BCI reorientation",
        "",
        f"- Among trials where BCI did reorient, incorrect trials had later BCI reorientation than correct trials: {bci_test['incorrect_median']:.1f} ms vs {bci_test['correct_median']:.1f} ms, delta {bci_test['incorrect_minus_correct_median']:.1f} ms, p={bci_test['p_value']:.3g}.",
        f"- The BCI-only incorrect-correct latency penalty was {no_ai_test['incorrect_minus_correct_median']:.1f} ms, p={no_ai_test['p_value']:.3g}.",
        f"- The median latency penalty was {interaction['incorrect_minus_correct_median']:.1f} ms larger in shared control than BCI-only; robust OLS interaction coefficient {interaction['ols_interaction_coefficient_ms']:.1f} ms, p={interaction['p_value']:.3g}.",
        f"- Among shared-control trials where both BCI input and executed output reoriented, the BCI-to-executed reorientation lag was {lag_test['incorrect_median']:.1f} ms for incorrect trials vs {lag_test['correct_median']:.1f} ms for correct trials, delta {lag_test['incorrect_minus_correct_median']:.1f} ms, p={lag_test['p_value']:.3g}.",
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(_argv: list[str] | None = None) -> int:
    summarize_two_mechanisms()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
